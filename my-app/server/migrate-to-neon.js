const Database = require("better-sqlite3");
const { neon } = require("@neondatabase/serverless");
const fs = require("node:fs");
const path = require("node:path");

async function main() {
  const databaseUrl = process.env.DATABASE_URL;
  if (!databaseUrl) {
    throw new Error("Set DATABASE_URL to the target Neon database connection string.");
  }

  const sqlitePath = path.resolve(
    process.env.SQLITE_PATH || path.join(__dirname, "database.sqlite")
  );
  if (!fs.existsSync(sqlitePath)) {
    throw new Error(`SQLite database file not found: ${sqlitePath}`);
  }

  const sqlite = new Database(sqlitePath, { readonly: true });
  const users = sqlite
    .prepare("SELECT id, name, email, password_hash FROM users ORDER BY id")
    .all();
  sqlite.close();

  const sql = neon(databaseUrl);
  await sql`
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      password_hash TEXT
    )
  `;
  await sql`
    CREATE TABLE IF NOT EXISTS password_reset_tokens (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
      token_hash TEXT NOT NULL UNIQUE,
      expires_at BIGINT NOT NULL
    )
  `;

  let imported = 0;
  let skipped = 0;

  for (const user of users) {
    const inserted = await sql`
      INSERT INTO users (id, name, email, password_hash)
      VALUES (${user.id}, ${user.name}, ${user.email}, ${user.password_hash})
      ON CONFLICT DO NOTHING
      RETURNING id
    `;

    if (inserted.length > 0) {
      imported += 1;
      continue;
    }

    const [existing] = await sql`
      SELECT id FROM users WHERE id = ${user.id} OR email = ${user.email}
    `;
    if (!existing) {
      throw new Error(
        `Could not import SQLite user ID ${user.id}; a conflicting database record exists.`
      );
    }
    skipped += 1;
  }

  await sql`
    SELECT setval(
      pg_get_serial_sequence('users', 'id'),
      COALESCE(MAX(id), 1),
      MAX(id) IS NOT NULL
    )
    FROM users
  `;

  console.log(`Migration complete. Imported ${imported} account(s); skipped ${skipped} existing account(s).`);
}

main().catch((error) => {
  console.error("SQLite to Neon migration failed:", error.message);
  process.exitCode = 1;
});
